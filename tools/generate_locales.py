"""Compile UTF-8 JSON catalogues into a dependency-free C++ lookup table (MIT)."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
def generate():
    files=sorted((ROOT/'assets/locales').glob('*.json'),key=lambda p:(p.stem!='en',p.stem))
    if not files or files[0].stem!='en':
        raise ValueError('The English source catalogue is required')
    catalogues=[]
    for p in files:
        data=json.loads(p.read_text(encoding='utf-8'))
        if not re.fullmatch(r'[a-z]{2,3}(?:-[a-z0-9]+)*',p.stem):
            raise ValueError(f'Invalid locale code: {p.stem}')
        if not isinstance(data.get('_name'),str):
            raise ValueError(f'Missing native language name: {p.name}')
        if any(not isinstance(v,str) for v in data.values()):
            raise ValueError(f'All messages must be strings: {p.name}')
        catalogues.append(data)
    source=catalogues[0]
    keys=sorted(k for k in source if not k.startswith('_'))
    for p,data in zip(files,catalogues):
        if set(data)-set(source):
            raise ValueError(f'Unknown message keys in {p.name}')
        for key in keys:
            if key in data and set(re.findall(r'\{(\w+)\}',data[key]))!=set(re.findall(r'\{(\w+)\}',source[key])):
                raise ValueError(f'Placeholder mismatch: {p.name}: {key}')
    for p in (ROOT/'src').glob('*.cpp'):
        for key in re.findall(r'\b(?:tr|notify)\("([a-z0-9_.]+)"\)',p.read_text(encoding='utf-8')):
            if key not in source:
                raise ValueError(f'Unknown message key in {p.name}: {key}')
    glyphs={int(code) for code in re.findall(r'^\s*\{(\d+),',(ROOT/'include/cyvr/font_data.hpp').read_text(encoding='utf-8'),re.M)}
    for p,data in zip(files,catalogues):
        missing={ord(c) for message in data.values() for c in message if c not in '\n\r\t' and ord(c) not in glyphs}
        if missing:
            raise ValueError(f'{p.name}: extend the font atlas for '+', '.join(f'U+{c:04X}' for c in sorted(missing)))
    quote=lambda s:json.dumps(s,ensure_ascii=False)
    lines=['// SPDX-License-Identifier: MIT','// Generated by tools/generate_locales.py; edit assets/locales/*.json.',
           '#pragma once','#include "cyvr/locale.hpp"','#include <array>','namespace cyvr::locale_data {',
           'inline constexpr LocaleInfo locales[] = {']
    lines += ['    {'+quote(p.stem)+', '+quote(data['_name'])+'},' for p,data in zip(files,catalogues)]
    lines += ['};',f'struct Message {{ std::string_view key; std::array<const char *, {len(files)}> text; }};',
              'inline constexpr Message messages[] = {']
    for key in keys:
        values=', '.join(quote(data[key]) if key in data else 'nullptr' for data in catalogues)
        lines.append('    {'+quote(key)+', {'+values+'}},')
    lines += ['};','} // namespace cyvr::locale_data','']
    return '\n'.join(lines)

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'include/cyvr/locale_data.hpp'
    content=generate()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8')!=content:
            raise SystemExit('Locale data is stale; run python tools/generate_locales.py')
    else:
        target.write_text(content,encoding='utf-8')
    print('Locale catalogues verified' if args.check else 'Locale lookup table generated')
