"""Bake the redistributed OFL Noto font. Runtime needs neither Python nor a font library."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(ROOT / "assets/fonts/NotoSans-Regular.ttf"), 48)
codes = sorted(set(range(32, 127)) | set(range(160, 256)) | {0x152, 0x153, 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2190, 0x2192, 0x2197, 0x2212, 0x2713})
atlas = Image.new("L", (1024, 1024), 0)
draw = ImageDraw.Draw(atlas)
draw.rectangle((0, 0, 3, 3), fill=255)
x, y, row = 8, 8, 0
records = []
for code in codes:
    char = chr(code)
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    width, height = right - left, bottom - top
    if x + width + 4 >= 1024:
        x, y, row = 8, y + row + 6, 0
    if y + height >= 1024:
        raise RuntimeError("Font atlas overflow")
    if width and height:
        draw.text((x - left, y - top), char, font=font, fill=255, anchor="ls")
    records.append(f"    {{{code}, {x}, {y}, {width}, {height}, {left}, {top}, {font.getlength(char):.5f}f}},")
    x += width + 6
    row = max(row, height)
(ROOT / "include/cyvr").mkdir(parents=True, exist_ok=True)
(ROOT / "include/cyvr/font_data.hpp").write_text("// Generated by tools/bake_font.py from Noto Sans (SIL OFL 1.1).\n#pragma once\n#include <cstdint>\nnamespace cyvr {\nstruct Glyph { uint32_t code; int x, y, w, h, left, top; float advance; };\ninline constexpr Glyph glyphs[] = {\n" + "\n".join(records) + "\n};\n}\n", encoding="utf-8")
(ROOT / "assets/font_atlas.bin").write_bytes(atlas.tobytes())
print(f"Baked {len(records)} glyphs into a 1024 x 1024 R8 atlas")
